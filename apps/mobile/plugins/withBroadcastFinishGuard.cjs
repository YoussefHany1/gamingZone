/**
 * Expo Config Plugin — "Broadcast already finished" crash guard
 *
 * Android can kill the app with:
 *
 *   java.lang.IllegalStateException: Broadcast already finished
 *     at android.content.BroadcastReceiver$PendingResult.sendFinished(...)
 *     at android.content.BroadcastReceiver$PendingResult$1.run(...)
 *     at android.app.QueuedWork.processPendingWork(...)
 *
 * When a BroadcastReceiver uses goAsync() and finishes its PendingResult while
 * QueuedWork still has pending work, the framework defers sendFinished() to the
 * QueuedWork thread. If the broadcast was already finished by then (a known
 * framework race, https://issuetracker.google.com/issues/257513022), the
 * deferred call throws on that thread and takes down the whole process even
 * though the broadcast result was already delivered.
 *
 * expo-notifications, WorkManager, Firebase Cloud Messaging and media-session
 * receivers all use goAsync(), so patching one library is not enough. The
 * guard below filters exactly this framework error and forwards everything
 * else to the previous handler (Crashlytics), keeping normal crash reporting.
 *
 * This must live in a config plugin: `android/` is generated by `expo prebuild`
 * and is git-ignored, so editing MainApplication.kt directly disappears on
 * every EAS build.
 *
 * Usage in app.json:
 *   "plugins": ["./plugins/withBroadcastFinishGuard.cjs"]
 */

const { withMainApplication } = require("expo/config-plugins");

const MARKER = "installBroadcastFinishCrashGuard";

const KOTLIN_HELPERS = `
  /**
   * Ignores the benign Android framework race that throws
   * \`IllegalStateException: Broadcast already finished\` from the QueuedWork
   * thread. The broadcast was already finished by the system, so there is no
   * work left to do — but without this guard the exception kills the app.
   *
   * Everything else is delegated to the previously installed handler, which
   * is normally Firebase Crashlytics, so real crashes are still reported.
   */
  private fun installBroadcastFinishCrashGuard() {
    val previousHandler = Thread.getDefaultUncaughtExceptionHandler()
    Thread.setDefaultUncaughtExceptionHandler { thread, throwable ->
      if (isBroadcastAlreadyFinishedError(throwable)) {
        android.util.Log.w(
          "BroadcastFinishGuard",
          "Ignored 'Broadcast already finished' on thread \${thread.name}",
        )
        recordBroadcastFinishNonFatal(throwable)
        return@setDefaultUncaughtExceptionHandler
      }
      if (previousHandler != null) {
        previousHandler.uncaughtException(thread, throwable)
      } else {
        throwable.printStackTrace()
      }
    }
  }

  private fun isBroadcastAlreadyFinishedError(throwable: Throwable): Boolean {
    var cause: Throwable? = throwable
    while (cause != null) {
      if (
        cause is IllegalStateException &&
        cause.message == "Broadcast already finished" &&
        cause.stackTrace.any {
          it.className.startsWith("android.content.BroadcastReceiver")
        }
      ) {
        return true
      }
      cause = cause.cause
    }
    return false
  }

  /** Reports the filtered framework race as a non-fatal Crashlytics event. */
  private fun recordBroadcastFinishNonFatal(throwable: Throwable) {
    try {
      val crashlytics =
        Class
          .forName("com.google.firebase.crashlytics.FirebaseCrashlytics")
          .getMethod("getInstance")
          .invoke(null)
      crashlytics
        ?.javaClass
        ?.getMethod("recordException", Throwable::class.java)
        ?.invoke(crashlytics, throwable)
    } catch (ignored: Throwable) {
      // Crashlytics is optional; never let reporting break the guard.
    }
  }
`;

const JAVA_HELPERS = `
  /**
   * Ignores the benign Android framework race that throws
   * \`IllegalStateException: Broadcast already finished\` from the QueuedWork
   * thread. Everything else is delegated to the previous handler.
   */
  private static void installBroadcastFinishCrashGuard() {
    final Thread.UncaughtExceptionHandler previousHandler =
        Thread.getDefaultUncaughtExceptionHandler();
    Thread.setDefaultUncaughtExceptionHandler(
        (thread, throwable) -> {
          if (isBroadcastAlreadyFinishedError(throwable)) {
            android.util.Log.w(
                "BroadcastFinishGuard",
                "Ignored 'Broadcast already finished' on thread " + thread.getName());
            recordBroadcastFinishNonFatal(throwable);
            return;
          }
          if (previousHandler != null) {
            previousHandler.uncaughtException(thread, throwable);
          } else {
            throwable.printStackTrace();
          }
        });
  }

  private static boolean isBroadcastAlreadyFinishedError(Throwable throwable) {
    Throwable cause = throwable;
    while (cause != null) {
      if (cause instanceof IllegalStateException
          && "Broadcast already finished".equals(cause.getMessage())) {
        for (StackTraceElement element : cause.getStackTrace()) {
          if (element.getClassName().startsWith("android.content.BroadcastReceiver")) {
            return true;
          }
        }
      }
      cause = cause.getCause();
    }
    return false;
  }

  private static void recordBroadcastFinishNonFatal(Throwable throwable) {
    try {
      Object crashlytics =
          Class.forName("com.google.firebase.crashlytics.FirebaseCrashlytics")
              .getMethod("getInstance")
              .invoke(null);
      if (crashlytics != null) {
        crashlytics
            .getClass()
            .getMethod("recordException", Throwable.class)
            .invoke(crashlytics, throwable);
      }
    } catch (Throwable ignored) {
      // Crashlytics is optional; never let reporting break the guard.
    }
  }
`;

/** Inserts the install call as late as possible in onCreate(), after RN init. */
function insertCallAfterInit(contents, call) {
  const anchors = [
    "ApplicationLifecycleDispatcher.onApplicationCreate(this)",
    "loadReactNative(this)",
    "super.onCreate()",
  ];

  for (const anchor of anchors) {
    const index = contents.indexOf(anchor);
    if (index === -1) continue;

    const lineEnd = contents.indexOf("\n", index);
    const insertAt = lineEnd === -1 ? contents.length : lineEnd + 1;
    return (
      contents.slice(0, insertAt) +
      call +
      "\n" +
      contents.slice(insertAt)
    );
  }

  throw new Error(
    "[withBroadcastFinishGuard] Could not find onCreate() in MainApplication",
  );
}

/** Appends helper methods just before the last closing brace of the class. */
function appendHelpers(contents, helpers) {
  const lastBrace = contents.lastIndexOf("}");
  if (lastBrace === -1) {
    throw new Error(
      "[withBroadcastFinishGuard] Could not find class end in MainApplication",
    );
  }
  return (
    contents.slice(0, lastBrace) +
    helpers +
    "\n" +
    contents.slice(lastBrace)
  );
}

function patchMainApplication(contents, filename) {
  if (contents.includes(MARKER)) return contents;

  const isKotlin = filename.endsWith(".kt");
  const call = isKotlin
    ? `    ${MARKER}()\n`
    : `    ${MARKER}();\n`;

  let result = insertCallAfterInit(contents, call);
  result = appendHelpers(result, isKotlin ? KOTLIN_HELPERS : JAVA_HELPERS);
  return result;
}

const withBroadcastFinishGuard = (config) =>
  withMainApplication(config, (mod) => {
    mod.modResults.contents = patchMainApplication(
      mod.modResults.contents,
      mod.modResults.path,
    );
    return mod;
  });

module.exports = withBroadcastFinishGuard;
module.exports.patchMainApplication = patchMainApplication;
